#!/usr/bin/env node
// Generates a local-only qualification test; never include its output in the native patch.
import { mkdir, readFile, writeFile, realpath, stat, lstat } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const MARKER = '// @generated by pi-mcp-elicitation/prepare-native-test.mjs; local qualification only; v1\n';
const slash = path => path.replaceAll('\\', '/');
async function exists(path) {
  try { await lstat(path); return true; }
  catch (error) { if (error.code === 'ENOENT') return false; throw error; }
}
async function file(path) {
  if (!(await stat(path)).isFile()) throw new Error(`Expected a file: ${path}`);
  return path;
}
async function manifest(root, name, version) {
  const path = await file(join(root, 'package.json'));
  const value = JSON.parse(await readFile(path, 'utf8'));
  if (value.name !== name || value.version !== version) {
    throw new Error(`Expected ${name}@${version} at ${path}; found ${value.name}@${value.version}`);
  }
  return value;
}

async function main() {
  const args = process.argv.slice(2);
  if (args.length !== 2) throw new Error('Usage: node prepare-native-test.mjs PI_CHECKOUT RPIV_ROOT');
  const checkout = await realpath(resolve(args[0]));
  const rpiv = await realpath(resolve(args[1]));
  const here = dirname(fileURLToPath(import.meta.url));
  const siblingRoot = resolve(here, '..');
  const companion = await realpath(siblingRoot);
  const codingAgent = join(checkout, 'packages/coding-agent');
  await manifest(codingAgent, '@earendil-works/pi-coding-agent', '1.3.0');
  const rpivManifest = await manifest(rpiv, '@juicesharp/rpiv-ask-user-question', '2.13.9');
  const companionManifest = await manifest(companion, 'pi-mcp-elicitation', '0.1.0');
  for (const [root, value] of [[rpiv, rpivManifest], [companion, companionManifest]]) {
    if (!value.pi?.extensions?.some(entry => entry === './index.ts' || entry === 'index.ts')) {
      throw new Error(`Expected package manifest to expose index.ts: ${root}`);
    }
    await file(join(root, 'index.ts'));
  }
  await file(join(companion, 'src/extension.mjs'));
  await file(join(checkout, 'node_modules/vitest/dist/cli.js'));
  await file(join(codingAgent, 'vitest.config.ts'));
  const replacements = {
    __HARNESS__: await file(join(codingAgent, 'test/suite/harness.ts')),
    __NATIVE__: await file(join(codingAgent, 'src/extensions/mcp/index.ts')),
    __LOADER__: await file(join(codingAgent, 'src/core/resource-loader.ts')),
    __SETTINGS__: await file(join(codingAgent, 'src/core/settings-manager.ts')),
    __RPIV_ROOT__: rpiv,
    __COMPANION_ROOT__: companion,
    __NATIVE_VALIDATOR__: await file(join(codingAgent, 'src/extensions/mcp/elicitation.ts')),
    __COMPANION_VALIDATOR__: await file(join(companion, 'src/form.mjs')),
    __CONTRACT_CASES__: await file(join(companion, 'test/contract-cases.mjs')),
  };
  const targetDir = join(codingAgent, 'test/suite');
  await mkdir(targetDir, { recursive: true });
  const generatedPaths = [];
  for (const [fixture, output] of [
    ['native.fixture.mjs', 'aituning-elicitation.integration.test.mjs'],
    ['contract.native.fixture.mjs', 'aituning-contract.integration.test.mjs'],
  ]) {
    let source = await readFile(await file(join(siblingRoot, 'test', fixture)), 'utf8');
    for (const [token, path] of Object.entries(replacements)) {
      source = source.replaceAll(`'${token}'`, JSON.stringify(slash(path)));
    }
    if (/__[A-Z_]+__/.test(source)) throw new Error('Unresolved fixture placeholder');
    const generated = MARKER + source.split(String.fromCharCode(13)).join('');
    const target = join(targetDir, output);
    const existing = await exists(target);
    if (existing) {
      const metadata = await lstat(target);
      if (!metadata.isFile() || metadata.isSymbolicLink()) throw new Error(`Refusing non-regular output: ${target}`);
      const old = await readFile(target, 'utf8');
      if (!old.startsWith(MARKER)) throw new Error(`Refusing to overwrite unowned output: ${target}`);
    }
    await writeFile(target, generated, { encoding: 'utf8', flag: existing ? 'w' : 'wx' });
    generatedPaths.push(slash(target));
  }
  process.stdout.write(`${JSON.stringify({ generated: generatedPaths, checkout: slash(checkout),
    rpivRoot: slash(rpiv), companionRoot: slash(companion), localOnly: true,
    command: 'node ../../node_modules/vitest/dist/cli.js --run test/suite/aituning-elicitation.integration.test.mjs test/suite/aituning-contract.integration.test.mjs',
    cwd: slash(codingAgent),
  })}\n`);
}

main().catch(error => {
  process.stderr.write(`prepare-native-test: ${error.message}\n`);
  process.exitCode = 1;
});

#!/usr/bin/env node
// Materialize only owned tests/config; never patch source or install/activate Pi.
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { lstat, mkdir, readFile, realpath, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const marker = '// @generated by pi-mcp-mirror/prepare-native-qualification.mjs; local qualification only; v1' + String.fromCharCode(10);
const here = dirname(fileURLToPath(import.meta.url));
const mirror = resolve(here, '..'), repo = resolve(mirror, '../..');
const slash = path => path.replaceAll(String.fromCharCode(92), '/');
async function ownedWrite(path, body) {
  let exists = false;
  try {
    const info = await lstat(path);
    exists = true;
    if (!info.isFile() || info.isSymbolicLink()) throw new Error(`Refusing non-regular output: ${path}`);
    if (!(await readFile(path, 'utf8')).startsWith(marker)) throw new Error(`Refusing unowned output: ${path}`);
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
  await writeFile(path, marker + body, { encoding: 'utf8', flag: exists ? 'w' : 'wx' });
}
async function main() {
  const args = process.argv.slice(2);
  if (args.length < 2 || args.length > 3) throw new Error('Usage: prepare-native-qualification.mjs PATCHED_PI_1_3_CHECKOUT RPIV_ROOT [OUT_DIR]');
  const checkout = await realpath(resolve(args[0])), rpiv = await realpath(resolve(args[1]));
  const protectedRelative = relative(resolve(repo, 'external'), checkout);
  if (!protectedRelative.startsWith('..') && !isAbsolute(protectedRelative)) throw new Error('external/ is read-only; use an isolated .scratch checkout');
  const coding = join(checkout, 'packages/coding-agent');
  const pkg = JSON.parse(await readFile(join(coding, 'package.json'), 'utf8'));
  if (pkg.name !== '@earendil-works/pi-coding-agent' || pkg.version !== '1.3.0') throw new Error('Expected source-layout Pi SDK 1.3.0, not an installed release');
  const pins = {
    'index.ts': '5a171a246151a7155d94e3182da6002cd434341a4ab26230844747efc91e1565',
    'runtime.ts': '13b729abd206b0587f75e25a719352ccf6cf8720cdea4fba0cb3aeb045d96aab',
    'elicitation.ts': 'e21dfa950390d19cf5a35924331625af06e926427df9e4db7deba6b416e90ef7',
  };
  for (const [name, pin] of Object.entries(pins)) {
    const hash = createHash('sha256').update(await readFile(join(coding, 'src/extensions/mcp', name))).digest('hex');
    if (hash !== pin) throw new Error(`Unqualified patched source ${name}: ${hash}`);
  }
  const prepared = spawnSync(process.execPath, [resolve(mirror, '../pi-mcp-elicitation/scripts/prepare-native-test.mjs'), checkout, rpiv], { stdio: 'inherit', windowsHide: true });
  if (prepared.error) throw prepared.error;
  if (prepared.status !== 0) throw new Error(`Companion fixture preparation failed (${prepared.status})`);
  const targets = [];
  for (const [fixture, target, replacements] of [
    ['manager-security.fixture.ts', 'aituning-manager-security.integration.test.ts', {
      __MIRROR_UI__: join(mirror, 'src/mcp/ui.ts'),
      __NATIVE_THEME__: join(coding, 'src/modes/interactive/theme/theme.ts'),
      __NATIVE_KEYBINDINGS__: join(coding, 'src/core/keybindings.ts'),
    }],
    ['logout-concurrency.fixture.ts', 'aituning-logout-concurrency.integration.test.ts', {
      __MIRROR_RUNTIME__: join(mirror, 'src/mcp/runtime.ts'),
    }],
  ]) {
    let body = await readFile(join(mirror, 'test', fixture), 'utf8');
    for (const [token, value] of Object.entries(replacements)) body = body.replaceAll('"' + token + '"', JSON.stringify(slash(value)));
    if (/__[A-Z_]+__/.test(body)) throw new Error(`Unresolved template: ${fixture}`);
    const path = join(coding, 'test/suite', target);
    await ownedWrite(path, body);
    targets.push(slash(path));
  }
  const aliases = [];
  for (const name of ['config', 'index', 'runtime', 'oauth', 'resources', 'tools', 'ui', 'elicitation']) {
    aliases.push({ find: '../src/extensions/mcp/' + name + '.ts', replacement: slash(join(mirror, 'src/mcp', name + '.ts')) });
    aliases.push({ find: slash(join(coding, 'src/extensions/mcp', name + '.ts')), replacement: slash(join(mirror, 'src/mcp', name + '.ts')) });
  }
  aliases.push({ find: '../src/core/tools/truncate.ts', replacement: slash(join(mirror, 'src/render/truncate.ts')) });
  let common = 'import base from ' + JSON.stringify(slash(join(coding, 'vitest.config.ts'))) + ';' + String.fromCharCode(10);
  const peerAliases = [
    ['@earendil-works/pi-coding-agent', join(coding, 'src/index.ts')],
    ['@earendil-works/pi-mcp', join(checkout, 'packages/mcp/src/index.ts')],
    ['@earendil-works/pi-mcp/oauth', join(checkout, 'packages/mcp/src/oauth/index.ts')],
    ['@earendil-works/pi-mcp/testing', join(checkout, 'packages/mcp/src/testing/index.ts')],
    ['@earendil-works/pi-tui', join(checkout, 'packages/tui/src/index.ts')],
  ];
  const peerCode = 'const peers = ' + JSON.stringify(peerAliases.map(([name, path]) => ({ find: '^' + name + '$', replacement: slash(path) }))) + '.map(a => ({ ...a, find: new RegExp(a.find) }));' + String.fromCharCode(10);
  common += peerCode;
  const out = resolve(args[2] ?? join(repo, '.scratch/pi-mcp-mirror/out'));
  await mkdir(out, { recursive: true });
  await ownedWrite(join(out, 'mirror.native.config.ts'), common + 'const aliases = ' + JSON.stringify(aliases) + ';' + String.fromCharCode(10) + 'export default { ...base, resolve: { ...base.resolve, alias: [...aliases, ...peers, ...(base.resolve?.alias ?? [])] } };' + String.fromCharCode(10));
  await ownedWrite(join(out, 'oracle.native.config.ts'), common + 'export default { ...base, resolve: { ...base.resolve, alias: [...peers, ...(base.resolve?.alias ?? [])] } };' + String.fromCharCode(10));
  console.log(JSON.stringify({ checkout: slash(checkout), out: slash(out), generated: targets, localOnly: true }));
}
main().catch(error => { console.error(`prepare-native-qualification: ${error.message}`); process.exitCode = 1; });
